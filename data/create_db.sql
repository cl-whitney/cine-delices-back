// Tables
DROP TABLE IF EXISTS "category", "quantity", "ingredient", "media", "user";

CREATE TABLE category (
  id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name            TEXT,
  recipe_id       TEXT NOT NULL
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ

);

CREATE TABLE quantity (
  id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  recipe_id       INTEGER,
  quantity        INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ
);

CREATE TABLE ingredient (
  id               INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name             TEXT,
  unity            TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ
);

CREATE TABLE media (
  id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  title        TEXT,
  type         TEXT,
  description  TEXT,
  label        TEXT,
  recipe_id    TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ
);

CREATE TABLE recipe (
  id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  title        TEXT NOT NULL,
  image        TEXT,
  description  TEXT,
  instruction  TEXT NOT NULL,
  duration     TEXT,
  difficulty   TEXT,
  cost         TEXT,
  status       TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ
);

CREATE TABLE user (
  id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  first_name       TEXT,
  last_name        TEXT,
  password         TEXT,
  email            TEXT,
  role             TEXT,
  status           TEXT,
  recipe_id        TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ
);

ALTER TABLE CATEGORIE ADD FOREIGN KEY (code_recette) REFERENCES RECETTE (code_recette);

ALTER TABLE COMPOSER ADD FOREIGN KEY (code_recette) REFERENCES RECETTE (code_recette);
ALTER TABLE COMPOSER ADD FOREIGN KEY (code_ingredient) REFERENCES INGREDIENT (code_ingredient);

ALTER TABLE MEDIA ADD FOREIGN KEY (code_recette) REFERENCES RECETTE (code_recette);

ALTER TABLE UTILISATEUR ADD FOREIGN KEY (code_recette) REFERENCES RECETTE (code_recette);


COMMIT;
